package main

import (
	"archive/tar"
	"compress/gzip"
	"fmt"
	"io"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"
)

var capabilities = []string{"httplib", "loadable_extensions"}

var extensions = []string{
	"autocomplete",
	"core_functions",
	"icu",
	"json",
	"parquet",
	"tpcds",
	"tpch",
}

// libraries derives archive names from registration names, with capabilities
// first in both link and registration order.
func libraries() []string {
	var names []string
	for _, name := range capabilities {
		names = append(names, "duckdb_"+name)
	}
	for _, name := range extensions {
		names = append(names, name+"_extension")
	}
	return names
}

var registrations = slices.Concat(capabilities, extensions)

// platformPrebuiltGo links a platform module's archives into its importer.
var platformPrebuiltGo = template.Must(template.New("").Parse(`//go:build {{.OS}} && {{.Arch}}

package duckdb_go_bindings_platform

/*
#cgo LDFLAGS: {{.LDFlags}} -L${SRCDIR}
*/
import "C"
`))

// staticExtensionLoaderC defines duckdb_register_static_extensions for the
// platform's extensions. cgo compiles it into the platform module.
var staticExtensionLoaderC = template.Must(template.New("").Parse(`#define DUCKDB_STATIC_BUILD
#include "duckdb_static_extension.h"

{{range .}}int32_t duckdb_extension_{{.}}_describe(duckdb_extension_descriptor *descriptor);
{{end}}
int32_t duckdb_register_static_extensions(void) {
	int32_t result = 0;
{{range .}}	result |= duckdb_register_static_extension(duckdb_extension_{{.}}_describe) != 0;
{{end}}	return result;
}
`))

// rootPrebuiltGo selects the platform module in the root module.
var rootPrebuiltGo = template.Must(template.New("").Parse(`//go:build !duckdb_use_lib && !duckdb_use_static_lib && {{.OS}} && {{.Arch}}

// Code generated by internal/cmd/brood; DO NOT EDIT.

package duckdb_go_bindings

import _ "{{.Module}}"
`))

func platformPrebuilt(platform string) []byte {
	goos, goarch, _ := strings.Cut(platform, "-")
	return render(platformPrebuiltGo, struct{ OS, Arch, LDFlags string }{goos, goarch, strings.Join(ldflags(goos), " ")})
}

// rootPrebuilt returns the root module's file that selects platform's module.
func (r *release) rootPrebuilt(platform string) (name string, data []byte) {
	goos, goarch, _ := strings.Cut(platform, "-")
	data = render(rootPrebuiltGo, struct{ OS, Arch, Module string }{goos, goarch, r.module(platform)})
	return "prebuilt_" + goos + "_" + goarch + ".go", data
}

// stage downloads platform's static archive and lays out its module in
// LIB_WORK/native/<platform>. The header goes to LIB_WORK/headers/<platform>,
// outside the module.
func (r *release) stage(platform string) {
	a := r.Platforms[platform]
	url := r.BaseURL + "/duckdb-static-libs-" + a.Static + ".tar.gz"
	archive, digest := r.archive(url, a.StaticSHA256)

	dest := r.native(platform)
	members := []string{"duckdb.h", "duckdb_static_extension.h", "libduckdb_static.a"}
	for _, lib := range libraries() {
		members = append(members, "lib"+lib+".a")
	}
	extract(archive, dest, members)
	mkdir(filepath.Dir(r.header(platform)))
	check(os.Rename(filepath.Join(dest, "duckdb.h"), r.header(platform)))

	writeFile(filepath.Join(dest, "prebuilt.go"), platformPrebuilt(platform))
	writeFile(filepath.Join(dest, "static_extension_loader.c"), render(staticExtensionLoaderC, registrations))
	writeFile(filepath.Join(dest, "go.mod"), fmt.Appendf(nil, "module %s\n\ngo %s\n", r.module(platform), r.goVersion))
	copyFile("LICENSE", filepath.Join(dest, "LICENSE"))

	provenance := map[string]string{"platform": platform, "sha256": digest, "url": url}
	if r.DuckDBVersion != "" { // unset for a BASE_URL override
		provenance["duckdb_version"] = r.DuckDBVersion
		provenance["source"] = r.Source
	}
	writeJSON(filepath.Join(dest, "provenance.json"), provenance)
}

// stageShared fetches the shared library and checks its header against the one
// used to compile the bindings (the pin, or the header installed by use).
func (r *release) stageShared(platform string) {
	a := r.Platforms[platform]
	archive, _ := r.archive(r.BaseURL+"/duckdb-shared-libs-"+a.Shared+".tar.gz", a.SharedSHA256)
	goos, _, _ := strings.Cut(platform, "-")
	members := map[string][]string{
		"darwin":  {"duckdb.h", "libduckdb.dylib"},
		"linux":   {"duckdb.h", "libduckdb.so"},
		"windows": {"duckdb.h", "duckdb.dll", "duckdb.lib"},
	}[goos]
	dest := r.dynamic(platform)
	extract(archive, dest, members)
	checkSameHeader("include/duckdb.h", filepath.Join(dest, "duckdb.h"))
}

// archive caches every native archive by its digest. Only pinned downloads can
// reuse the cache without a request; overrides must resolve their current bytes.
func (r *release) archive(url, pin string) (path, digest string) {
	dir := filepath.Join(r.work, "downloads")
	mkdir(dir)
	if pin != "" {
		path = filepath.Join(dir, pin+".tar.gz")
		if sha256File(path) == pin {
			return path, pin
		}
	}
	partial, err := os.CreateTemp(dir, "*.partial")
	check(err)
	check(partial.Close())
	download(url, partial.Name())
	digest = sha256File(partial.Name())
	if pin != "" && digest != pin {
		check(os.Remove(partial.Name()))
		fail("%s: SHA-256 %s, want %s", url, digest, pin)
	}
	path = filepath.Join(dir, digest+".tar.gz")
	check(os.Rename(partial.Name(), path))
	return path, digest
}

// ldflags returns the cgo linker flags for a platform module on goos.
func ldflags(goos string) []string {
	var flags []string
	if goos == "linux" {
		flags = append(flags, "-rdynamic")
	}
	for _, lib := range libraries() {
		flags = append(flags, "-l"+lib)
	}
	flags = append(flags, "-lduckdb_static")
	switch goos {
	case "darwin":
		flags = append(flags, "-lc++")
	case "linux":
		flags = append(flags, "-lstdc++", "-lm", "-ldl")
	case "windows":
		flags = append(flags, "-lws2_32", "-lwsock32", "-lrstrtmgr", "-lstdc++", "-lm", "--static")
	}
	return flags
}

// extract copies the named members of a .tar.gz archive into an emptied dir.
func extract(archive, dir string, names []string) {
	check(os.RemoveAll(dir))
	mkdir(dir)
	f, err := os.Open(archive)
	check(err)
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		fail("%s: %v", archive, err)
	}

	missing := make(map[string]bool)
	for _, name := range names {
		missing[name] = true
	}
	tr := tar.NewReader(gz)
	for len(missing) > 0 {
		hdr, err := tr.Next()
		if err == io.EOF {
			fail("%s lacks %s", archive, strings.Join(slices.Sorted(maps.Keys(missing)), ", "))
		}
		if err != nil {
			fail("%s: %v", archive, err)
		}
		if name := strings.TrimPrefix(hdr.Name, "./"); missing[name] {
			delete(missing, name)
			writeFrom(filepath.Join(dir, name), tr)
		}
	}
}
